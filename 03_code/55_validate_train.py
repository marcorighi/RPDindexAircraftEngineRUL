def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def safe_corr(x: np.ndarray, y: np.ndarray) -> float:
    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]
    y = y[mask]

    if len(x) < 2:
        return np.nan
    if np.ptp(x) == 0 or np.ptp(y) == 0:
        return np.nan

    return float(np.corrcoef(x, y)[0, 1])


def spearman_corr(x: np.ndarray, y: np.ndarray) -> float:
    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]
    y = y[mask]

    if len(x) < 2:
        return np.nan
    if np.ptp(x) == 0 or np.ptp(y) == 0:
        return np.nan

    xr = pd.Series(x).rank(method="average").to_numpy(dtype=float)
    yr = pd.Series(y).rank(method="average").to_numpy(dtype=float)
    return safe_corr(xr, yr)


def null_trajectory_metrics(
    y: np.ndarray,
    rul: np.ndarray,
    early_late_fraction: float,
) -> dict[str, float]:
    y = np.asarray(y, dtype=float)
    rul = np.asarray(rul, dtype=float)

    mask = np.isfinite(y) & np.isfinite(rul)
    y = y[mask]
    rul = rul[mask]
    n = len(y)

    if n == 0:
        return {metric: np.nan for metric in NULL_METRICS}

    pearson = safe_corr(y, rul)
    spearman = spearman_corr(y, rul)

    if n >= 2:
        dy = np.diff(y)
        inc = int(np.sum(dy > 0))
        dec = int(np.sum(dy < 0))
        monotonicity = abs(inc - dec) / (n - 1)
    else:
        monotonicity = np.nan

    k = max(1, int(math.ceil(n * early_late_fraction)))
    early = float(np.median(y[:k]))
    late = float(np.median(y[-k:]))

    return {
        "abs_spearman_rul": abs(spearman) if np.isfinite(spearman) else np.nan,
        "abs_pearson_rul": abs(pearson) if np.isfinite(pearson) else np.nan,
        "monotonicity": monotonicity,
        "abs_delta_late_early": abs(late - early),
    }


def rank_biserial_paired(diff: np.ndarray) -> float:
    """
    Matched-pairs rank-biserial correlation.

    Positive values mean the second member of the pair (global RPD) tends to
    have larger metric values than the first (local RPD).
    """
    diff = np.asarray(diff, dtype=float)
    diff = diff[np.isfinite(diff) & (diff != 0)]

    if len(diff) == 0:
        return np.nan

    ranks = pd.Series(np.abs(diff)).rank(method="average").to_numpy(dtype=float)
    w_plus = float(np.sum(ranks[diff > 0]))
    w_minus = float(np.sum(ranks[diff < 0]))
    den = w_plus + w_minus

    return (w_plus - w_minus) / den if den > 0 else np.nan


def wilcoxon_paired(a: np.ndarray, b: np.ndarray) -> float:
    if wilcoxon is None:
        return np.nan

    mask = np.isfinite(a) & np.isfinite(b)
    a = a[mask]
    b = b[mask]

    if len(a) < 2:
        return np.nan

    diff = b - a
    if not np.any(diff != 0):
        return 1.0

    try:
        return float(
            wilcoxon(
                b,
                a,
                alternative="two-sided",
                zero_method="wilcox",
                method="auto",
            ).pvalue
        )
    except TypeError:
        # Compatibility with older SciPy versions lacking method="auto".
        return float(
            wilcoxon(
                b,
                a,
                alternative="two-sided",
                zero_method="wilcox",
            ).pvalue
        )
    except Exception:
        return np.nan


def holm_adjust(p_values: Iterable[float]) -> np.ndarray:
    """
    Holm-Bonferroni adjusted p-values. NaN values remain NaN.
    """
    p = np.asarray(list(p_values), dtype=float)
    out = np.full_like(p, np.nan, dtype=float)

    finite_idx = np.flatnonzero(np.isfinite(p))
    if len(finite_idx) == 0:
        return out

    pv = p[finite_idx]
    order = np.argsort(pv)
    ordered = pv[order]

    m = len(ordered)
    adjusted_ordered = np.empty(m, dtype=float)

    running = 0.0
    for i, val in enumerate(ordered):
        adj = (m - i) * val
        running = max(running, adj)
        adjusted_ordered[i] = min(1.0, running)

    inverse = np.empty(m, dtype=int)
    inverse[order] = np.arange(m)
    out[finite_idx] = adjusted_ordered[inverse]
    return out


def engine_level_local_global(
    metrics: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Aggregate across informative sensors inside each engine, then compare the
    paired RPD variants across engines (n <= 100 independent units).
    """
    informative = metrics[metrics["informative_sensor_trajectory"]].copy()

    agg_spec = {metric: "median" for metric in COMPARISON_METRICS}
    engine_level = (
        informative.groupby(["id", "index", "family"], as_index=False)
        .agg(agg_spec)
        .sort_values(["id", "index"])
    )

    rows = []

    for local_name, global_name, variant in PAIRS:
        local = engine_level[engine_level["index"] == local_name].set_index("id")
        glob = engine_level[engine_level["index"] == global_name].set_index("id")
        common = local.index.intersection(glob.index)

        for metric in COMPARISON_METRICS:
            a = local.loc[common, metric].to_numpy(dtype=float)
            b = glob.loc[common, metric].to_numpy(dtype=float)
            mask = np.isfinite(a) & np.isfinite(b)
            a = a[mask]
            b = b[mask]
            diff = b - a

            rows.append(
                {
                    "variant": variant,
                    "local_index": local_name,
                    "global_index": global_name,
                    "metric": metric,
                    "engine_count": len(diff),
                    "local_median": float(np.median(a)) if len(a) else np.nan,
                    "global_median": float(np.median(b)) if len(b) else np.nan,
                    "median_global_minus_local": (
                        float(np.median(diff)) if len(diff) else np.nan
                    ),
                    "global_win_fraction": (
                        float(np.mean(diff > 0)) if len(diff) else np.nan
                    ),
                    "tie_fraction": (
                        float(np.mean(diff == 0)) if len(diff) else np.nan
                    ),
                    "rank_biserial_global_vs_local": (
                        rank_biserial_paired(diff) if len(diff) else np.nan
                    ),
                    "wilcoxon_p": wilcoxon_paired(a, b),
                }
            )

    tests = pd.DataFrame(rows)

    # Correct across the three local/global variants separately for each metric.
    tests["wilcoxon_p_holm_within_metric"] = np.nan
    for metric, idx in tests.groupby("metric").groups.items():
        idx = list(idx)
        tests.loc[idx, "wilcoxon_p_holm_within_metric"] = holm_adjust(
            tests.loc[idx, "wilcoxon_p"].to_numpy()
        )

    # Also provide a conservative correction across all engine-level tests.
    tests["wilcoxon_p_holm_all"] = holm_adjust(
        tests["wilcoxon_p"].to_numpy()
    )

    return engine_level, tests


def sensor_level_local_global(metrics: pd.DataFrame) -> pd.DataFrame:
    """
    Repeat paired local/global tests independently for each sensor using engines
    as replicates. Holm correction is applied within each variant x metric
    family across sensors.
    """
    informative = metrics[metrics["informative_sensor_trajectory"]].copy()
    rows = []

    for local_name, global_name, variant in PAIRS:
        local_all = informative[informative["index"] == local_name]
        global_all = informative[informative["index"] == global_name]

        sensors = sorted(set(local_all["sensor"]).intersection(global_all["sensor"]))

        for sensor in sensors:
            local = (
                local_all[local_all["sensor"] == sensor]
                .set_index("id")
                .sort_index()
            )
            glob = (
                global_all[global_all["sensor"] == sensor]
                .set_index("id")
                .sort_index()
            )
            common = local.index.intersection(glob.index)

            for metric in [
                "abs_spearman_rul",
                "abs_pearson_rul",
                "monotonicity",
            ]:
                a = local.loc[common, metric].to_numpy(dtype=float)
                b = glob.loc[common, metric].to_numpy(dtype=float)

                mask = np.isfinite(a) & np.isfinite(b)
                a = a[mask]
                b = b[mask]
                diff = b - a

                rows.append(
                    {
                        "variant": variant,
                        "local_index": local_name,
                        "global_index": global_name,
                        "sensor": sensor,
                        "metric": metric,
                        "engine_count": len(diff),
                        "local_median": (
                            float(np.median(a)) if len(a) else np.nan
                        ),
                        "global_median": (
                            float(np.median(b)) if len(b) else np.nan
                        ),
                        "median_global_minus_local": (
                            float(np.median(diff)) if len(diff) else np.nan
                        ),
                        "global_win_fraction": (
                            float(np.mean(diff > 0)) if len(diff) else np.nan
                        ),
                        "rank_biserial_global_vs_local": (
                            rank_biserial_paired(diff) if len(diff) else np.nan
                        ),
                        "wilcoxon_p": wilcoxon_paired(a, b),
                    }
                )

    tests = pd.DataFrame(rows)
    tests["wilcoxon_p_holm"] = np.nan

    for (_, _), idx in tests.groupby(["variant", "metric"]).groups.items():
        idx = list(idx)
        tests.loc[idx, "wilcoxon_p_holm"] = holm_adjust(
            tests.loc[idx, "wilcoxon_p"].to_numpy()
        )

    return tests


def read_train(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)

    required = ["id", "cycle", *SENSOR_COLUMNS]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"{path} does not have the expected named columns. Missing: {missing}"
        )

    return df.sort_values(["id", "cycle"]).reset_index(drop=True)


def build_shuffle_tasks(
    raw: pd.DataFrame,
    eps: float,
    max_groups: int,
) -> list[tuple[int, str, np.ndarray, np.ndarray]]:
    tasks = []

    for engine_id, g in raw.groupby("id", sort=True):
        g = g.sort_values("cycle")
        cycles = g["cycle"].to_numpy(dtype=int)
        failure_cycle = int(cycles[-1])

        # progressive_indices returns prefixes x[:2] ... x[:T], so the metric
        # vector aligns with cycles[1:].
        rul = failure_cycle - cycles[1:]

        for sensor in SENSOR_COLUMNS:
            values = g[sensor].to_numpy(dtype=float)
            if not np.all(np.isfinite(values)):
                continue

            if float(np.std(values, ddof=0)) <= eps:
                continue

            tasks.append(
                (
                    int(engine_id),
                    sensor,
                    values,
                    rul.astype(float),
                )
            )

    if max_groups > 0:
        tasks = tasks[:max_groups]

    return tasks


def _shuffle_worker(
    task: tuple[int, str, np.ndarray, np.ndarray],
    permutations: int,
    base_seed: int,
    early_late_fraction: float,
) -> tuple[int, str, list[tuple]]:
    engine_id, sensor, values, rul = task
    sensor_number = int(sensor[1:])

    # Stable seed independent of process scheduling.
    seed_seq = np.random.SeedSequence(
        [int(base_seed), int(engine_id), int(sensor_number)]
    )
    rng = np.random.default_rng(seed_seq)

    rows: list[tuple] = []

    for permutation_id in range(1, permutations + 1):
        shuffled = rng.permutation(values)
        trajectories = progressive_indices(shuffled.tolist())

        for index_name in GLOBAL_INDICES:
            y = np.asarray(trajectories[index_name], dtype=float)
            m = null_trajectory_metrics(y, rul, early_late_fraction)

            rows.append(
                (
                    engine_id,
                    sensor,
                    permutation_id,
                    index_name,
                    m["abs_spearman_rul"],
                    m["abs_pearson_rul"],
                    m["monotonicity"],
                    m["abs_delta_late_early"],
                )
            )

    return engine_id, sensor, rows


def run_temporal_shuffle(
    tasks: list[tuple[int, str, np.ndarray, np.ndarray]],
    output_path: Path,
    permutations: int,
    seed: int,
    jobs: int,
    early_late_fraction: float,
) -> None:
    header = [
        "id",
        "sensor",
        "permutation",
        "index",
        *NULL_METRICS,
    ]

    start = time.perf_counter()
    completed = 0
    total = len(tasks)

    with gzip.open(output_path, "wt", newline="", encoding="utf-8") as gz:
        writer = csv.writer(gz)
        writer.writerow(header)

        if jobs == 1:
            for task in tasks:
                _, _, rows = _shuffle_worker(
                    task,
                    permutations,
                    seed,
                    early_late_fraction,
                )
                writer.writerows(rows)
                completed += 1

                if completed % 25 == 0 or completed == total:
                    elapsed = time.perf_counter() - start
                    rate = completed / elapsed if elapsed > 0 else 0
                    remaining = (
                        (total - completed) / rate if rate > 0 else np.nan
                    )
                    print(
                        f"[INFO] shuffle groups {completed}/{total}; "
                        f"elapsed={elapsed:.1f}s; ETA={remaining:.1f}s"
                    )
        else:
            with ProcessPoolExecutor(max_workers=jobs) as pool:
                futures = [
                    pool.submit(
                        _shuffle_worker,
                        task,
                        permutations,
                        seed,
                        early_late_fraction,
                    )
                    for task in tasks
                ]

                for future in as_completed(futures):
                    _, _, rows = future.result()
                    writer.writerows(rows)
                    completed += 1

                    if completed % 25 == 0 or completed == total:
                        elapsed = time.perf_counter() - start
                        rate = completed / elapsed if elapsed > 0 else 0
                        remaining = (
                            (total - completed) / rate if rate > 0 else np.nan
                        )
                        print(
                            f"[INFO] shuffle groups {completed}/{total}; "
                            f"elapsed={elapsed:.1f}s; ETA={remaining:.1f}s"
                        )


def temporal_shuffle_summaries(
    null_path: Path,
    real_metrics: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    null = pd.read_csv(null_path)

    real = real_metrics[
        real_metrics["informative_sensor_trajectory"]
        & real_metrics["index"].isin(GLOBAL_INDICES)
    ].copy()

    # Restrict real results to exactly the groups present in the null run.
    null_groups = null[["id", "sensor"]].drop_duplicates()
    real = real.merge(null_groups, on=["id", "sensor"], how="inner")

    # ------------------------------------------------------------------
    # 1) Per engine/sensor/index observed vs its own null distribution.
    # ------------------------------------------------------------------
    group_rows = []

    null_grouped = null.groupby(["id", "sensor", "index"], sort=False)
    real_lookup = real.set_index(["id", "sensor", "index"])

    for key, g in null_grouped:
        if key not in real_lookup.index:
            continue

        r = real_lookup.loc[key]
        if isinstance(r, pd.DataFrame):
            r = r.iloc[0]

        row = {
            "id": key[0],
            "sensor": key[1],
            "index": key[2],
        }

        for metric in NULL_METRICS:
            observed = float(r[metric])
            a = g[metric].to_numpy(dtype=float)
            a = a[np.isfinite(a)]

            if len(a):
                null_median = float(np.median(a))
                q025 = float(np.quantile(a, 0.025))
                q975 = float(np.quantile(a, 0.975))
                p_upper = float(
                    (1 + np.sum(a >= observed)) / (len(a) + 1)
                )
            else:
                null_median = q025 = q975 = p_upper = np.nan

            row[f"observed_{metric}"] = observed
            row[f"null_median_{metric}"] = null_median
            row[f"null_q025_{metric}"] = q025
            row[f"null_q975_{metric}"] = q975
            row[f"observed_minus_null_median_{metric}"] = (
                observed - null_median
                if np.isfinite(observed) and np.isfinite(null_median)
                else np.nan
            )
            row[f"empirical_p_upper_{metric}"] = p_upper

        group_rows.append(row)

    by_group = pd.DataFrame(group_rows)

    # ------------------------------------------------------------------
    # 2) Engine-level null aggregates:
    #    sensors -> median within engine for each permutation/index.
    # ------------------------------------------------------------------
    engine_null = (
        null.groupby(["permutation", "index", "id"], as_index=False)[NULL_METRICS]
        .median()
        .sort_values(["permutation", "index", "id"])
    )

    # Observed engine-level statistics, same aggregation.
    engine_real = (
        real.groupby(["index", "id"], as_index=False)[NULL_METRICS]
        .median()
        .sort_values(["index", "id"])
    )

    # ------------------------------------------------------------------
    # 3) Dataset-level test:
    #    engine-level medians -> median across engines.
    #
    # This makes the engine, not the sensor, the inferential unit.
    # ------------------------------------------------------------------
    null_dataset = (
        engine_null.groupby(["permutation", "index"], as_index=False)[NULL_METRICS]
        .median()
    )
    real_dataset = (
        engine_real.groupby("index", as_index=False)[NULL_METRICS]
        .median()
        .set_index("index")
    )

    dataset_rows = []

    for index_name in GLOBAL_INDICES:
        g = null_dataset[null_dataset["index"] == index_name]

        if index_name not in real_dataset.index:
            continue

        for metric in NULL_METRICS:
            observed = float(real_dataset.loc[index_name, metric])
            a = g[metric].to_numpy(dtype=float)
            a = a[np.isfinite(a)]

            if len(a):
                null_median = float(np.median(a))
                q025 = float(np.quantile(a, 0.025))
                q975 = float(np.quantile(a, 0.975))
                empirical_p = float(
                    (1 + np.sum(a >= observed)) / (len(a) + 1)
                )
            else:
                null_median = q025 = q975 = empirical_p = np.nan

            dataset_rows.append(
                {
                    "index": index_name,
                    "metric": metric,
                    "engine_count": int(
                        engine_real[engine_real["index"] == index_name]["id"]
                        .nunique()
                    ),
                    "permutations": len(a),
                    "observed_engine_median": observed,
                    "null_median": null_median,
                    "null_q025": q025,
                    "null_q975": q975,
                    "observed_minus_null_median": (
                        observed - null_median
                        if np.isfinite(observed) and np.isfinite(null_median)
                        else np.nan
                    ),
                    "empirical_p_upper": empirical_p,
                }
            )

    dataset_summary = pd.DataFrame(dataset_rows)

    return by_group, engine_null, dataset_summary


def main() -> int:
    args = parse_args()

    raw_path = args.raw_train.resolve()
    metrics_path = args.metrics.resolve()
    output_dir = args.output_dir.resolve()

    if args.permutations < 1:
        print("[ERROR] --permutations must be >= 1.", file=sys.stderr)
        return 2

    if args.jobs < 1:
        print("[ERROR] --jobs must be >= 1.", file=sys.stderr)
        return 2

    if not (0 < args.early_late_fraction <= 0.5):
        print(
            "[ERROR] --early-late-fraction must be in (0, 0.5].",
            file=sys.stderr,
        )
        return 2

    for path in [raw_path, metrics_path]:
        if not path.exists():
            print(f"[ERROR] Missing input: {path}", file=sys.stderr)
            return 2

    output_dir.mkdir(parents=True, exist_ok=True)

    files = {
        "engine_level_metrics":
            output_dir / "08_RPD_engine_level_metrics.csv",
        "engine_level_tests":
            output_dir / "09_RPD_engine_level_local_global_tests.csv",
        "sensor_level_tests":
            output_dir / "10_RPD_sensor_level_local_global_tests.csv",
        "temporal_shuffle_null":
            output_dir / "11_RPD_temporal_shuffle_null.csv.gz",
        "temporal_shuffle_by_engine_sensor":
            output_dir / "12_RPD_temporal_shuffle_by_engine_sensor.csv",
        "temporal_shuffle_engine_aggregates":
            output_dir / "13_RPD_temporal_shuffle_engine_aggregates.csv.gz",
        "temporal_shuffle_dataset_level":
            output_dir / "14_RPD_temporal_shuffle_dataset_level.csv",
        "manifest":
            output_dir / "55_validation_manifest.json",
    }

    print("RPD training-set robust validation")
    print(f"Raw train:    {raw_path}")
    print(f"Metrics:      {metrics_path}")
    print(f"Output:       {output_dir}")
    print(f"Permutations: {args.permutations}")
    print(f"Seed:         {args.seed}")
    print(f"Workers:      {args.jobs}")
    if args.max_groups > 0:
        print(
            f"[WARN] DEBUG MODE: only first {args.max_groups} informative "
            "engine/sensor groups will be shuffled."
        )
    print()

    metrics = pd.read_csv(metrics_path)

    required_metric_cols = {
        "id",
        "sensor",
        "index",
        "family",
        "informative_sensor_trajectory",
        *COMPARISON_METRICS,
    }
    missing = sorted(required_metric_cols.difference(metrics.columns))
    if missing:
        print(
            f"[ERROR] Metrics file missing columns: {missing}",
            file=sys.stderr,
        )
        return 2

    # A) Engine-level and per-sensor local/global validation.
    engine_level, engine_tests = engine_level_local_global(metrics)
    sensor_tests = sensor_level_local_global(metrics)

    engine_level.to_csv(files["engine_level_metrics"], index=False)
    engine_tests.to_csv(files["engine_level_tests"], index=False)
    sensor_tests.to_csv(files["sensor_level_tests"], index=False)

    print(
        f"[OK] Engine-level local/global analysis: "
        f"{files['engine_level_tests']}"
    )
    print(
        f"[OK] Sensor-level local/global analysis: "
        f"{files['sensor_level_tests']}"
    )

    # B) Temporal-shuffle null experiment.
    raw = read_train(raw_path)
    tasks = build_shuffle_tasks(
        raw,
        args.sensor_std_eps,
        args.max_groups,
    )

    print(
        f"[INFO] temporal-shuffle informative engine/sensor groups: "
        f"{len(tasks)}"
    )

    run_temporal_shuffle(
        tasks=tasks,
        output_path=files["temporal_shuffle_null"],
        permutations=args.permutations,
        seed=args.seed,
        jobs=args.jobs,
        early_late_fraction=args.early_late_fraction,
    )

    print(f"[OK] Raw null distribution: {files['temporal_shuffle_null']}")

    by_group, engine_null, dataset_summary = temporal_shuffle_summaries(
        files["temporal_shuffle_null"],
        metrics,
    )

    by_group.to_csv(
        files["temporal_shuffle_by_engine_sensor"],
        index=False,
    )
    engine_null.to_csv(
        files["temporal_shuffle_engine_aggregates"],
        index=False,
        compression="gzip",
    )
    dataset_summary.to_csv(
        files["temporal_shuffle_dataset_level"],
        index=False,
    )

    print(
        f"[OK] Per engine/sensor null comparison: "
        f"{files['temporal_shuffle_by_engine_sensor']}"
    )
    print(
        f"[OK] Engine-level null aggregates: "
        f"{files['temporal_shuffle_engine_aggregates']}"
    )
    print(
        f"[OK] Dataset-level temporal-shuffle test: "
        f"{files['temporal_shuffle_dataset_level']}"
    )

    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "script": Path(__file__).name,
        "python_version": platform.python_version(),
        "numpy_version": np.__version__,
        "pandas_version": pd.__version__,
        "scipy_wilcoxon_available": wilcoxon is not None,
        "raw_train_file": str(raw_path),
        "raw_train_sha256": sha256(raw_path),
        "metrics_file": str(metrics_path),
        "metrics_sha256": sha256(metrics_path),
        "computeindex_file": str(
            (Path(__file__).resolve().parent / "computeindex_optimized.py")
        ),
        "computeindex_sha256": sha256(
            Path(__file__).resolve().parent / "computeindex_optimized.py"
        ),
        "software_doi": "10.5281/zenodo.21892421",
        "technical_report_doi": "10.5281/zenodo.21898684",
        "permutations": args.permutations,
        "base_seed": args.seed,
        "workers": args.jobs,
        "early_late_fraction": args.early_late_fraction,
        "sensor_std_eps": args.sensor_std_eps,
        "max_groups_debug_limit": args.max_groups,
        "shuffle_group_count": len(tasks),
        "global_indices": GLOBAL_INDICES,
        "null_metrics": NULL_METRICS,
        "engine_as_primary_inferential_unit": True,
        "temporal_shuffle_null":
            "Within each engine/sensor, permute the complete raw sensor "
            "sequence while preserving its values and length; recompute "
            "progressive global RPD trajectories.",
        "dataset_level_null_aggregation":
            "Median across informative sensors within engine, then median "
            "across engines for each permutation.",
        "test_set_used": False,
        "truth_set_used": False,
        "outputs": {
            key: str(path)
            for key, path in files.items()
            if key != "manifest"
        },
    }

    files["manifest"].write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    print(f"[OK] Manifest: {files['manifest']}")
    print()

    print("Engine-level local/global tests:")
    with pd.option_context(
        "display.max_columns", None,
        "display.width", 180,
        "display.float_format", "{:.6g}".format,
    ):
        print(
            engine_tests[
                [
                    "variant",
                    "metric",
                    "engine_count",
                    "local_median",
                    "global_median",
                    "median_global_minus_local",
                    "global_win_fraction",
                    "rank_biserial_global_vs_local",
                    "wilcoxon_p_holm_all",
                ]
            ].to_string(index=False)
        )

    print()
    print("Dataset-level temporal-shuffle test:")
    with pd.option_context(
        "display.max_columns", None,
        "display.width", 180,
        "display.float_format", "{:.6g}".format,
    ):
        print(dataset_summary.to_string(index=False))

    if wilcoxon is None:
        print()
        print(
            "[WARN] SciPy is unavailable. Wilcoxon p-values are NaN; "
            "the shuffle experiment is unaffected."
        )

    print()
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
