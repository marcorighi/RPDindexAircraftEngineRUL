#!/usr/bin/env python3
"""
55_validate_train.py

Robust validation of the training-set RPD findings.

This script performs two complementary analyses:

A) ENGINE-LEVEL LOCAL-vs-GLOBAL COMPARISON
   The engine is treated as the independent experimental unit.
   Metrics are first aggregated across informative sensors within each engine,
   then paired local/global RPD variants are compared across engines.

B) TEMPORAL-SHUFFLE NULL EXPERIMENT FOR GLOBAL RPD INDICES
   For each informative engine/sensor series, the raw sensor values are
   randomly permuted in time, the progressive RPD indices are recomputed with
   computeindex_optimized.py, and the resulting degradation metrics are compared
   with the observed temporal ordering.

The temporal-shuffle test preserves:
    - the engine,
    - the sensor,
    - the number of cycles,
    - the exact marginal distribution of sensor values,

while destroying temporal ordering. Therefore it directly tests whether the
observed RPD/RUL association depends on degradation-related temporal structure
rather than merely on progressive sample accumulation.

IMPORTANT
---------
- PM_test.csv and PM_truth.csv are NOT read.
- The optimized RPD implementation is imported from computeindex_optimized.py.
- Randomization is deterministic for a fixed seed.
- Default Monte Carlo permutations: 100.
- Engine-level aggregation is used for the principal inferential summaries to
  avoid treating engine/sensor observations as fully independent replicates.

Expected project layout
-----------------------
02_raw_data/
    PM_train.csv

03_code/
    computeindex_optimized.py
    50_analyze_train.py
    55_validate_train.py

04_results/05_tables/
    01_RPD_metrics_by_engine_sensor.csv

Outputs
-------
04_results/05_tables/
    08_RPD_engine_level_metrics.csv
    09_RPD_engine_level_local_global_tests.csv
    10_RPD_sensor_level_local_global_tests.csv
    11_RPD_temporal_shuffle_null.csv.gz
    12_RPD_temporal_shuffle_by_engine_sensor.csv
    13_RPD_temporal_shuffle_engine_aggregates.csv.gz
    14_RPD_temporal_shuffle_dataset_level.csv
    55_validation_manifest.json
"""

